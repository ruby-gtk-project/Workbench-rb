#!/usr/bin/env ruby
# frozen_string_literal: true

require 'json'
require 'fileutils'

# Ported from upstream's build-aux/library.js, which Meson runs at build time
# to turn the un-vendored `demos/` git submodule (workbenchdev/demos.git) into
# `$pkgdatadir/demos/index.json` plus a per-demo directory tree. This gem has
# no Meson install step to run that script at build time, so this script does
# the same job ahead of time against a checkout of that submodule, and its
# output is committed into `data/demos` directly — the same slot
# LibraryWindow.demos_dir already reads from.
#
# Usage: ruby build-aux/vendor_demos.rb /path/to/workbenchdev/demos/src
#
# Re-run this (then `git add data/demos`) whenever the demos submodule should
# be refreshed to a newer upstream commit.

# Build artifacts upstream's own copyDemo skips — generated by compiling a
# demo, not part of its source, and meaningless to ship.
EXCLUDED_FILES = %w[
  Cargo.lock
  Cargo.toml
  lib.rs
  workbench.rs
  workbench.vala
  libworkbenchcode.so
  settings
  main.ui
  icons.gresource
  icons.gresource.xml
].freeze

def languages_for(demo_dir)
  languages = []
  languages << 'javascript' if File.exist?(File.join(demo_dir, 'main.js'))
  languages << 'typescript' if File.exist?(File.join(demo_dir, 'main.ts'))
  languages << 'vala' if File.exist?(File.join(demo_dir, 'main.vala'))
  languages << 'rust' if File.exist?(File.join(demo_dir, 'code.rs'))
  languages << 'python' if File.exist?(File.join(demo_dir, 'main.py'))
  languages
end

def copy_demo(source, destination)
  FileUtils.mkdir_p(destination)
  Dir.children(source).each do |name|
    next if name.start_with?('.')
    next if EXCLUDED_FILES.include?(name)

    src_path = File.join(source, name)
    dst_path = File.join(destination, name)
    File.directory?(src_path) ? copy_demo(src_path, dst_path) : FileUtils.cp(src_path, dst_path)
  end
end

def sort_key(demo)
  return [0, ''] if demo['name'] == 'Welcome'
  return [1, ''] if demo['name'] == 'Platform Tools'

  [2, demo['name']]
end

source_root = ARGV.fetch(0) { abort 'usage: vendor_demos.rb /path/to/demos/src' }
dest_root = File.expand_path('../data/demos', __dir__)

FileUtils.rm_rf(dest_root)
FileUtils.mkdir_p(dest_root)

demos = Dir.children(source_root).sort.filter_map do |name|
  next if name.start_with?('.')

  demo_dir = File.join(source_root, name)
  next unless File.directory?(demo_dir)

  manifest_path = File.join(demo_dir, 'main.json')
  next unless File.exist?(manifest_path)

  demo = JSON.parse(File.read(manifest_path))
  demo['name'] = name
  demo['languages'] = languages_for(demo_dir)

  copy_demo(demo_dir, File.join(dest_root, name))
  demo
end

demos.sort_by! { |demo| sort_key(demo) }

File.write(File.join(dest_root, 'index.json'), JSON.generate(demos))

puts "Vendored #{demos.size} demos into #{dest_root}"
